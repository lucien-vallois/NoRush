async (page) => {
  const base = 'http://localhost:3001';
  const api = 'http://localhost:3000';
  const passed = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const ensure = (condition, message) => { if (!condition) throw new Error(message); };
  const ready = async (route, heading) => {
    await page.goto(base + route);
    await page.getByRole('heading', { name: heading, exact: true }).waitFor();
    await page.waitForLoadState('networkidle');
  };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base + '/profile');
  await page.getByRole('heading', { name: /^(Perfil|Bem-vindo ao NoRush\.)$/ }).waitFor();
  if (page.url().endsWith('/profile')) await page.getByRole('button', { name: 'Sair da plataforma', exact: true }).click();
  await page.getByRole('heading', { name: 'Bem-vindo ao NoRush.' }).waitFor();
  await page.getByRole('textbox', { name: 'E-mail de acesso' }).fill('operador@flowback.com');
  await page.getByRole('textbox', { name: 'Senha', exact: true }).fill('incorrect-password');
  await page.getByRole('button', { name: 'Entrar na plataforma' }).click();
  await page.getByRole('alert').getByText('E-mail ou senha incorretos. Tente novamente.').waitFor();
  passed.push('wrong login displays an actionable error');
  await page.getByRole('button', { name: 'Preencher acesso de demonstração' }).click();
  await page.getByRole('button', { name: 'Entrar na plataforma' }).click();
  await page.getByRole('heading', { name: 'Visão operacional.', exact: true }).waitFor();
  await page.waitForLoadState('networkidle');
  ensure(await page.getByRole('button', { name: /^FK-01 / }).count() === 1, 'Tank selection missing');
  await page.getByRole('button', { name: /^FK-01 / }).click();
  ensure(await page.getByRole('button', { name: /^FK-01 / }).getAttribute('aria-pressed') === 'true', 'Tank did not become selected');
  passed.push('operator login and dashboard selection');
  await page.screenshot({ path: 'output/playwright/dashboard-desktop.png', fullPage: true });

  await ready('/tanks', 'Tanques');
  await page.getByRole('button', { name: 'Ver detalhes do tanque FK-01', exact: true }).click();
  const tankDialog = page.getByRole('dialog', { name: 'FK-01', exact: true });
  await tankDialog.waitFor();
  ensure(await tankDialog.evaluate(node => node.contains(document.activeElement)), 'Dialog did not receive focus');
  await page.keyboard.press('Tab');
  ensure(await tankDialog.evaluate(node => node.matches(':modal') && (node.contains(document.activeElement) || document.activeElement === document.body)), 'Focus moved into the background application');
  await page.keyboard.press('Escape');
  await tankDialog.waitFor({ state: 'hidden' });
  passed.push('tank detail uses native modality and closes with Escape');
  await page.screenshot({ path: 'output/playwright/tanks-desktop.png', fullPage: true });

  await ready('/sensors', 'Sensores');
  await page.getByRole('textbox', { name: 'Buscar sensor por ID ou nome' }).fill('SENSOR-001');
  ensure(await page.getByText('SENSOR-001', { exact: true }).count() >= 1, 'Expected sensor missing');
  ensure(await page.getByText('SENSOR-002', { exact: true }).count() === 0, 'Sensor filter did not apply');
  passed.push('sensor search filters the table');
  await page.getByRole('textbox', { name: 'Buscar sensor por ID ou nome' }).fill('');
  await page.screenshot({ path: 'output/playwright/sensors-desktop.png', fullPage: true });

  await ready('/readings', 'Leituras');
  await page.getByRole('combobox', { name: 'Período do histórico' }).selectOption('30d');
  await page.waitForLoadState('networkidle');
  await page.waitForFunction(() => document.querySelector('.recharts-area-curve')?.getAttribute('d')?.length > 10 || document.querySelectorAll('.recharts-area-dot').length > 0);
  passed.push('historical chart renders actual SVG data');
  const selector = page.getByRole('combobox', { name: 'Sensor do histórico' });
  const options = await selector.locator('option').allTextContents();
  const interfaceLabel = options.find(label => label.includes('Float Stick'));
  ensure(interfaceLabel, 'Interface sensor missing from selector');
  await selector.selectOption({ label: interfaceLabel });
  await page.waitForLoadState('networkidle');
  await page.getByText('Camada de água', { exact: true }).waitFor();
  passed.push('oil/water interface sensor displays its series');
  await page.screenshot({ path: 'output/playwright/readings-desktop.png', fullPage: true });

  const login = await page.request.post(api + '/auth/login', { data: { email: 'admin@flowback.com', password: 'admin123' } });
  ensure(login.ok(), 'Administrator fixture login failed');
  const admin = await login.json();
  const headers = { Authorization: 'Bearer ' + admin.accessToken };
  const tankResponse = await page.request.get(api + '/tanks', { headers });
  const tank = (await tankResponse.json()).find(item => item.status === 'active');
  const title = 'Validação visual NoRush ' + Date.now();
  const fixture = await page.request.post(api + '/alerts', { headers, data: { type: 'sensor_error', severity: 'low', title, message: 'Ocorrência sintética criada exclusivamente para a revisão da interface.', tankId: tank.id, metadata: { source: 'norush-browser-smoke', simulated: true } } });
  ensure(fixture.status() === 201, 'Could not create isolated UI fixture');
  const syntheticAlert = await fixture.json();
  await ready('/alerts', 'Central de alertas.');
  await page.getByRole('textbox', { name: 'Buscar alertas por título ou mensagem' }).fill(title);
  await page.getByRole('button', { name: 'Reconhecer alerta ' + title + ' de ' + tank.code, exact: true }).click();
  await page.getByRole('row').filter({ hasText: title }).getByText('Reconhecido', { exact: true }).waitFor();
  passed.push('search and recognition of an isolated synthetic alert');
  await page.getByRole('button', { name: 'Resolver alerta ' + title + ' de ' + tank.code, exact: true }).click();
  const resolution = page.getByRole('dialog', { name: 'Registrar resolução' });
  await resolution.waitFor();
  await resolution.getByRole('textbox', { name: 'Medida adotada' }).fill('Revisão visual concluída no ambiente simulado; nenhum equipamento de campo foi acionado.');
  await resolution.getByRole('button', { name: 'Confirmar resolução', exact: true }).click();
  await resolution.waitFor({ state: 'hidden' });
  await page.getByRole('row').filter({ hasText: title }).getByText('Resolvido', { exact: true }).waitFor();
  passed.push('resolution modal persists operator notes');
  await page.getByRole('button', { name: 'Limpar filtros', exact: true }).click();
  await page.getByRole('table').waitFor();
  const rowsBefore = page.getByRole('table').getByRole('row');
  ensure(await rowsBefore.count() > 1, 'Alert table is empty before pagination');
  const firstRowBefore = await rowsBefore.nth(1).innerText();
  await page.getByRole('button', { name: 'Próxima página de alertas' }).click();
  await page.getByText(/^Página 2 de/).waitFor();
  await page.getByRole('table').waitFor();
  const rowsAfter = page.getByRole('table').getByRole('row');
  ensure(await rowsAfter.count() > 1, 'Alert table is empty after pagination');
  ensure(await rowsAfter.nth(1).innerText() !== firstRowBefore, 'Pagination did not load different records');
  await page.getByRole('button', { name: 'Página anterior de alertas' }).click();
  await page.getByText(/^Página 1 de/).waitFor();
  await page.getByRole('table').waitFor();
  await page.screenshot({ path: 'output/playwright/alerts-desktop.png', fullPage: true });
  passed.push('alert pagination advances and returns');

  await page.setViewportSize({ width: 390, height: 844 });
  const responsive = [];
  for (const [route, heading] of [['/dashboard', 'Visão operacional.'], ['/tanks', 'Tanques'], ['/sensors', 'Sensores'], ['/readings', 'Leituras'], ['/alerts', 'Central de alertas.'], ['/profile', 'Perfil']]) {
    await ready(route, heading);
    const dimensions = await page.evaluate(() => ({ content: document.documentElement.scrollWidth, viewport: innerWidth }));
    ensure(dimensions.content <= dimensions.viewport, 'Horizontal overflow on ' + route + ': ' + JSON.stringify(dimensions));
    responsive.push(route);
  }
  passed.push('six routes fit a 390px viewport without page overflow');
  await ready('/dashboard', 'Visão operacional.');
  await page.getByRole('button', { name: 'Abrir navegação' }).click();
  await page.getByRole('complementary', { name: 'Navegação principal' }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('complementary', { name: 'Navegação principal' }).waitFor({ state: 'hidden' });
  passed.push('mobile navigation opens and closes with Escape');
  await page.screenshot({ path: 'output/playwright/dashboard-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Ativar tema escuro' }).click();
  ensure(await page.evaluate(() => document.documentElement.classList.contains('dark')), 'Dark theme failed');
  await page.screenshot({ path: 'output/playwright/dashboard-dark.png', fullPage: true });
  await page.getByRole('button', { name: 'Ativar tema claro' }).click();
  passed.push('light and dark theme controls work');
  await ready('/profile', 'Perfil');
  await page.getByRole('button', { name: 'Sair da plataforma', exact: true }).click();
  await page.getByRole('heading', { name: 'Bem-vindo ao NoRush.' }).waitFor();
  passed.push('logout returns to login');
  ensure(errors.length === 0, 'Uncaught browser errors: ' + errors.join('; '));
  await page.screenshot({ path: 'output/playwright/login-desktop.png', fullPage: true });
  return { result: 'PASS', checks: passed.length, passed, responsive, javascriptErrors: errors, retainedSyntheticAlert: syntheticAlert.id, utc: new Date().toISOString() };
}


